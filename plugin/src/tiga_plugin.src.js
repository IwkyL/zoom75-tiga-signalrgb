//
// Plugin for the Zoom75 TIGA running the patched stock firmware v1.1 (patch v1
// out/patched.hex on the cable; patch v2 out_v2/patched_v2.hex, SHA-256
// 1f1f1c46...e59d, also over the 2.4G receiver). Speaks SRGBmods QMK protocol 1.0.6
// on the raw HID interface (interface 1, usage page 0xFF60, usage 0x61) of either
// device.
//
// Differences from the SRGBmods template (Keychron_V1_Max_QMK_ANSI_Encoder_Keyboard.js):
// - No "Shutdown Mode / Shutdown Color": the firmware returns to its own effect
//   2 s after the last packet, so a shutdown colour would not stay.
// - No extra "VIA" read: the patch sends exactly one reply per query, although it
//   reports firmware type 2 (VIA).
// - Streams only after the handshake matched (protocol 1.0.6, 86 LEDs, type 1 or 2),
//   so it sends no colour packets to a keyboard without the patch.
// - Sends 0x25 (mode on) again before streaming if Shutdown sent 0x26 and
//   SignalRGB keeps rendering (e.g. after system resume).
//
// On the cable (Radio = false) the plugin sends exactly what v1.0.1 sent: a full
// frame of 10 packets per Render(). The 2.4G receiver carries about one packet per
// 75-100 ms (hardware, 2026-10-21, V2_STEP6_RESULTS.md), so there (Radio = true):
// - at most one packet per Render(), at least 80 ms after the previous packet of any
//   kind (100 ms after 0x25 / 0x26): a 9-LED group not sent for 3 s first, else the
//   next changed group (round robin), else, in a still scene, the group sent longest
//   ago once 1.5 s old (repairs lost packets and the indicators the firmware draws,
//   and feeds the firmware's 2 s timeout);
// - 0x25 is sent as 25 01 (patch v2 quiet switch: no reply to 0x24 / 0x25 / 0x26),
//   once per session; 0x26 once at shutdown. 0x23, 0x25, 0x26 and 0x27 are one flipped
//   bit away from VIA writes, so they are sent as seldom as possible; 0x23 not at all;
//   the handshake starts with 0x22 and stops at the first reply that is not SignalRGB;
// - handshake: stale reports flushed, one query at a time, up to 250 ms per reply, the
//   next packet at least 150 ms after a query and 80 ms after its reply;
// - replies are read every Render(): an exact echo of a colour packet means the
//   keyboard lost its radio state (quiet is off again) and gets one 25 01; 0xFF + a
//   copy of a packet means the keyboard is not in 2.4G mode any more (VIA got it; e.g.
//   after the cable was plugged in or out): streaming stops, the user is told to press
//   Fn+V, and the handshake is retried (every 5 s five times, then every 10 s);
// - a colour packet whose bytes 6-7 happen to form a valid vendor CRC frame gets one
//   colour LSB flipped, so the receiver never sees a valid CRC-framed packet.
//
// LED table generated by tools/gen_tiga_layout.py from the firmware's g_led_config
