export function Initialize()
{
	handshakeOk = false;
	modeEnabled = false;
	handshakeRetries = 0;

	if(Radio)
	{
		resetRadio();
	}

	tryHandshake();
}

export function Render()
{
	if(!handshakeOk)
	{
		if(Radio)
		{
			retryRadio();

			return;
		}

		// Retry a few times, e.g. if VIA or the Console held the interface at start.
		if(handshakeRetries < HandshakeMaxRetries && Date.now() - lastHandshakeTime >= HandshakeRetryMs)
		{
			handshakeRetries++;
			tryHandshake();
		}

		return;
	}

	if(Radio)
	{
		renderRadio();

		return;
	}

	if(!modeEnabled)
	{
		effectEnable();
	}

	sendColors();
}

export function Shutdown(SystemSuspending)
{
	// Hand the LEDs back to the keyboard's own effect. If 0x26 never arrives
	// (unplug, crash), the firmware does the same by itself after 2 s.
	if(handshakeOk)
	{
		effectDisable();
	}

	logLine(`Shutdown (system suspending: ${SystemSuspending ? "yes" : "no"})`);
}

function tryHandshake()
{
	lastHandshakeTime = Date.now();
	handshakeOk = Radio ? handshakeRadio() : handshake();

	if(handshakeOk)
	{
		if(alertId !== null)
		{
			device.denotify(alertId);
			alertId = null;
		}

		effectEnable();
	}
}

function handshake()
{
	drainReads();

	const type = query(CmdFirmwareType);
	const qmk = query(CmdQMKVersion);
	const proto = query(CmdProtocolVersion);
	const uid = query(CmdUniqueIdentifier);
	const leds = query(CmdTotalLeds);

	if(type === null || qmk === null || proto === null || uid === null || leds === null)
	{
		return handshakeFailed("No SignalRGB reply. Is the patched firmware flashed, the cable plugged in, and VIA, the Meletrix Console and the Wuque DFU tool closed?");
	}

	const firmwareType = type[2];
	logLine(`Firmware Type: ${firmwareType === VIAFirmware ? "VIA" : firmwareType === MainlineQMKFirmware ? "Mainline" : firmwareType}`);
	logLine(`QMK Version: ${qmk[2]}.${qmk[3]}.${qmk[4]}`);

	const protocolVersion = `${proto[2]}.${proto[3]}.${proto[4]}`;
	logLine(`SignalRGB Protocol Version: ${protocolVersion}`);

	if(!(uid[2] === 0 && uid[3] === 0 && uid[4] === 0))
	{
		logLine(`Unique Device Identifier: ${uid[2]}.${uid[3]}.${uid[4]}`);
	}

	const ledCount = leds[2];
	logLine(`Device Total LED Count: ${ledCount}`);

	if(firmwareType !== MainlineQMKFirmware && firmwareType !== VIAFirmware)
	{
		return handshakeFailed(`Unknown firmware type ${firmwareType}.`);
	}

	if(protocolVersion !== PluginProtocolVersion)
	{
		return handshakeFailed(`This plugin needs SignalRGB protocol ${PluginProtocolVersion}; the keyboard reports ${protocolVersion}.`);
	}

	if(ledCount !== TotalLeds)
	{
		return handshakeFailed(`The keyboard reports ${ledCount} LEDs; this plugin expects ${TotalLeds}.`);
	}

	logLine(`Plugin Version: ${Version()}`);

	return true;
}

function handshakeFailed(message)
{
	// Radio: retried every 10 s for as long as SignalRGB runs, so log a repeated
	// failure only every 10 minutes.
	if(!Radio || message !== lastFailure || Date.now() - lastFailureAt >= 60 * RadioLogEveryMs)
	{
		logLine(`Handshake failed: ${message} Not streaming.`);
		lastFailure = message;
		lastFailureAt = Date.now();
	}

	if(alertId === null)
	{
		alertId = device.notify(`${DeviceLabel}: SignalRGB not active`, message, 1);
	}

	return false;
}

// Send a one-byte query and wait for the reply whose first byte echoes it.
// Replies are 32 bytes; device.read puts the report ID at [0], so the command is at [1].
function query(command)
{
	device.write([0x00, command], PacketLength);

	for(let attempt = 0; attempt < 4; attempt++)
	{
		const data = device.read([0x00], PacketLength, ReadTimeoutMs);

		if(device.getLastReadSize() <= 0)
		{
			break;
		}

		if(data[1] === command)
		{
			return data;
		}

		logLine(`Ignoring packet 0x${hex(data[1])} while waiting for 0x${hex(command)}`);
	}

	logLine(`No reply to 0x${hex(command)}`);

	return null;
}

function drainReads()
{
	for(let i = 0; i < 16; i++)
	{
		device.read([0x00], PacketLength, 0);

		if(device.getLastReadSize() <= 0)
		{
			break;
		}
	}
}

function effectEnable() // SignalRGB mode on (also restarts the 2 s timeout)
{
	if(Radio)
	{
		radioWrite([0x00, CmdModeEnable, RadioQuiet], RadioCommandGapMs);
		modeEnabled = true;
		logLine("Mode on, quiet (0x25 01)");

		return;
	}

	device.write([0x00, CmdModeEnable], PacketLength);
	modeEnabled = true;
	logLine("Mode on (0x25)");
}

function effectDisable() // Back to the keyboard's own effect
{
	if(Radio)
	{
		radioWrite([0x00, CmdModeDisable], RadioCommandGapMs);
		modeEnabled = false;
		logLine("Mode off (0x26)");

		return;
	}

	device.write([0x00, CmdModeDisable], PacketLength);
	modeEnabled = false;
	logLine("Mode off (0x26)");
}

// Also written to SignalRGB's log file (Logs\ in the app folder), so a session can be
// checked afterwards. Nothing here runs per frame.
function logLine(message)
{
	device.log(`[TIGA] ${message}`, {toFile: true});
}

function grabColors()
{
	const rgbdata = new Array(TotalLeds * 3).fill(0);
	const forced = LightingMode === "Forced" ? hexToRgb(forcedColor) : null;

	for(let iIdx = 0; iIdx < vLeds.length; iIdx++)
	{
		const color = forced !== null ? forced : device.color(vLedPositions[iIdx][0], vLedPositions[iIdx][1]);
		const iLedIdx = vLeds[iIdx] * 3;
		rgbdata[iLedIdx] = color[0];
		rgbdata[iLedIdx + 1] = color[1];
		rgbdata[iLedIdx + 2] = color[2];
	}

	return rgbdata;
}

// 86 LEDs = 9 packets of 9 LEDs + 1 packet of 5: [0x24, start, count, R,G,B x count].
function sendColors()
{
	const rgbdata = grabColors();

	for(let start = 0; start < TotalLeds; start += LedsPerPacket)
	{
		const count = Math.min(LedsPerPacket, TotalLeds - start);
		const packet = [0x00, CmdStreamRGBData, start, count].concat(rgbdata.slice(start * 3, (start + count) * 3));
		device.write(packet, PacketLength);
	}
}

// ---- 2.4G receiver ----------------------------------------------------------------

function resetRadio()
{
	nextSendAt = 0;
	resetGroups();
	recentPackets = [];
	selfHealDue = false;
	selfHealAt = -Infinity;
	rareLog = {};
}

function resetGroups()
{
	sentGroups = new Array(Groups).fill(null);
	sentAt = new Array(Groups).fill(null);
	groupCursor = 0;
}

// Every radio write goes through here: waits until the previous packet is far enough
// back (blocking only in the handshake and Shutdown; Render never calls it early).
function radioWrite(data, gapAfterMs)
{
	const wait = nextSendAt - Date.now();

	if(wait > 0)
	{
		device.pause(wait);
	}

	device.write(data, PacketLength);
	nextSendAt = Date.now() + gapAfterMs;
	recentPackets.push(padPayload(data.slice(1)));

	if(recentPackets.length > RadioRecentPackets)
	{
		recentPackets.shift();
	}
}

function retryRadio()
{
	const delay = handshakeRetries < HandshakeMaxRetries ? HandshakeRetryMs : RadioSlowRetryMs;

	if(Date.now() - lastHandshakeTime >= delay)
	{
		handshakeRetries++;
		tryHandshake();
	}
}

// One query at a time: returns its reply, "via" when the keyboard answered through VIA
// (0xFF and a zero body: not in 2.4G mode, or no patch v2), or null.
function queryRadio(command)
{
	radioWrite([0x00, command], RadioQueryGapMs);

	const sentAt = Date.now();
	const deadline = sentAt + RadioReplyTimeoutMs;

	for(let left = RadioReplyTimeoutMs; left > 0; left = deadline - Date.now())
	{
		const data = toBytes(device.read([0x00], PacketLength, left), 0, PacketLength);

		if(device.getLastReadSize() <= 0)
		{
			break;
		}

		nextSendAt = Math.max(nextSendAt, Date.now() + RadioGapMs);

		if(data[1] === command)
		{
			return data;
		}

		if(data[1] === 0xFF && data.slice(2).every(b => b === 0))
		{
			logRare("via", `Reply to 0x${hex(command)} after ${Date.now() - sentAt} ms: ff + zeros (VIA got the query: not in 2.4G mode, or the query arrived damaged)`, 60 * RadioLogEveryMs);

			return "via";
		}

		logLine(`Ignoring packet 0x${hex(data[1])} while waiting for 0x${hex(command)}`);
	}

	logLine(`No reply to 0x${hex(command)} within ${RadioReplyTimeoutMs} ms`);

	return null;
}

function handshakeRadio()
{
	drainReads();

	// 0x22 first: it has no one-bit neighbour that is a VIA write, and while the keyboard
	// is not in 2.4G mode (or asleep) it is the only packet a retry sends.
	const proto = queryRadio(CmdProtocolVersion);

	if(proto === "via")
	{
		return handshakeFailed("The keyboard answers over 2.4G, but not as SignalRGB: it is not in 2.4G mode (cable plugged in: the cable plugin takes over; otherwise unplug the cable and press Fn+V, needed after every plug or unplug), or patch v2 is not flashed.");
	}

	if(proto === null)
	{
		return handshakeFailed("No reply over 2.4G. Is the keyboard on and awake (press a key), in 2.4G mode (Fn+V), patch v2 flashed, and VIA, the Meletrix Console and the Wuque tools closed?");
	}

	const protocolVersion = `${proto[2]}.${proto[3]}.${proto[4]}`;
	logLine(`SignalRGB Protocol Version: ${protocolVersion}`);

	if(protocolVersion !== PluginProtocolVersion)
	{
		return handshakeFailed(`This plugin needs SignalRGB protocol ${PluginProtocolVersion}; the keyboard reports ${protocolVersion}.`);
	}

	const type = queryRadio(CmdFirmwareType);
	const qmk = isReply(type) ? queryRadio(CmdQMKVersion) : null;
	const leds = isReply(qmk) ? queryRadio(CmdTotalLeds) : null;

	if(!isReply(type) || !isReply(qmk) || !isReply(leds))
	{
		const what = [[CmdFirmwareType, type], [CmdQMKVersion, qmk], [CmdTotalLeds, leds]]
			.map(q => `0x${hex(q[0])} ${isReply(q[1]) ? "ok" : q[1] === "via" ? "VIA" : "none"}`).join(", ");

		return handshakeFailed(`Incomplete SignalRGB reply over 2.4G (${what}). Retrying.`);
	}

	const firmwareType = type[2];
	logLine(`Firmware Type: ${firmwareType === VIAFirmware ? "VIA" : firmwareType === MainlineQMKFirmware ? "Mainline" : firmwareType}`);
	logLine(`QMK Version: ${qmk[2]}.${qmk[3]}.${qmk[4]}`);

	const ledCount = leds[2];
	logLine(`Device Total LED Count: ${ledCount}`);

	if(firmwareType !== MainlineQMKFirmware && firmwareType !== VIAFirmware)
	{
		return handshakeFailed(`Unknown firmware type ${firmwareType}.`);
	}

	if(ledCount !== TotalLeds)
	{
		return handshakeFailed(`The keyboard reports ${ledCount} LEDs; this plugin expects ${TotalLeds}.`);
	}

	logLine(`Plugin Version: ${Version()}`);
	handshakeRetries = 0;
	resetGroups();

	return true;
}

function renderRadio()
{
	readRadioReplies();

	if(!handshakeOk)
	{
		return;
	}

	const now = Date.now();

	if(now < nextSendAt)
	{
		return;
	}

	if(!modeEnabled || selfHealDue)
	{
		selfHealDue = false;
		effectEnable();

		return;
	}

	const packets = groupPackets(grabColors());
	const g = pickGroup(now, packets);

	if(g < 0)
	{
		return;
	}

	const wire = packets[g].slice();

	if(isVendorFrame(wire))
	{
		wire[3] ^= 1;               // one colour LSB: the CRC no longer matches
		logRare("crc", "Colour packet nudged: its bytes 6-7 formed a valid vendor CRC");
	}

	radioWrite([0x00].concat(wire), RadioGapMs);
	sentGroups[g] = packets[g].join(",");
	sentAt[g] = now;
	groupCursor = (g + 1) % Groups;
}

// The 32-byte payloads of the 10 colour packets, zero-padded.
function groupPackets(rgbdata)
{
	const packets = [];

	for(let start = 0; start < TotalLeds; start += LedsPerPacket)
	{
		const count = Math.min(LedsPerPacket, TotalLeds - start);
		packets.push(padPayload([CmdStreamRGBData, start, count].concat(rgbdata.slice(start * 3, (start + count) * 3))));
	}

	return packets;
}

// tools/srgb_hidtest.py GroupScheduler: overdue group, else next changed group (round
// robin), else the stalest group once RadioRefreshMs old, else none (-1).
function pickGroup(now, packets)
{
	let stalest = -1;

	for(let g = 0; g < Groups; g++)
	{
		if(sentAt[g] !== null && (stalest < 0 || sentAt[g] < sentAt[stalest]))
		{
			stalest = g;
		}
	}

	if(stalest >= 0 && now - sentAt[stalest] >= RadioOverdueMs)
	{
		return stalest;
	}

	for(let k = 0; k < Groups; k++)
	{
		const g = (groupCursor + k) % Groups;

		if(packets[g].join(",") !== sentGroups[g])
		{
			return g;
		}
	}

	if(stalest >= 0 && now - sentAt[stalest] >= RadioRefreshMs)
	{
		return stalest;
	}

	return -1;
}

function readRadioReplies()
{
	for(let i = 0; i < RadioReadsPerRender && handshakeOk; i++)
	{
		const data = device.read([0x00], PacketLength, 0);

		if(device.getLastReadSize() <= 0)
		{
			return;
		}

		handleRadioReply(toBytes(data, 1, PacketLength));
	}
}

// With quiet on, patch v2 replies only to queries, and with 24 FD / 24 FE to a colour
// packet that arrived damaged. Anything else tells the plugin something.
function handleRadioReply(reply)
{
	const body = reply.slice(1).join(",");

	if(reply[0] === 0xFF)
	{
		if(recentPackets.some(p => p.slice(1).join(",") === body))
		{
			radioModeLost();
		}
		else
		{
			logRare("ff", "Damaged 0xFF reply ignored");
		}

		return;
	}

	if(reply[0] === CmdStreamRGBData && (reply[1] === 0xFD || reply[1] === 0xFE))
	{
		logRare("err", `Reply 24 ${hex(reply[1])}: a colour packet arrived damaged`);

		return;
	}

	if(reply[0] === CmdStreamRGBData && recentPackets.some(p => p.join(",") === reply.join(",")))
	{
		// Quiet was on, so the keyboard lost its radio state (power-on defaults: mode
		// off, quiet off). One 25 01 restores both.
		if(Date.now() - selfHealAt >= RadioSelfHealMs)
		{
			selfHealAt = Date.now();
			selfHealDue = true;
			nextSendAt = Math.max(nextSendAt, Date.now() + RadioGapMs);     // echoes use the link too
			logLine("The keyboard echoed a colour packet: its radio state was reset. Sending 25 01 once.");
		}

		return;
	}

	logRare("other", `Unexpected reply ${reply.slice(0, 4).map(hex).join(" ")}`);
}

function radioModeLost()
{
	logLine("The keyboard handed a packet to VIA (0xFF reply): it is not in 2.4G mode any more (cable plugged in, BT, or the cable was unplugged without Fn+V). Streaming over 2.4G stops until the handshake passes again.");
	handshakeOk = false;
	modeEnabled = false;
	handshakeRetries = 0;
	lastHandshakeTime = Date.now();
	resetGroups();

	if(alertId === null)
	{
		alertId = device.notify(`${DeviceLabel}: SignalRGB paused`, "The keyboard is not in 2.4G mode. With the cable plugged in, the cable plugin takes over. For 2.4G: unplug the cable and press Fn+V (needed after every plug or unplug).", 1);
	}
}

function logRare(kind, message, everyMs = RadioLogEveryMs)
{
	const s = rareLog[kind] || (rareLog[kind] = {last: -Infinity, count: 0});
	const now = Date.now();
	s.count++;

	if(now - s.last >= everyMs)
	{
		logLine(`${message} (${s.count}x since the last such line)`);
		s.last = now;
		s.count = 0;
	}
}

function isReply(r)
{
	return r !== null && r !== "via";
}

// device.read's result as a plain array of bytes from..to-1 (missing ones 0). Only indexing
// is used on it: SignalRGB does not return a plain Array (on 2026-10-21 Array.isArray() was
// false for a correct reply, so the first 2.4G handshake failed).
function toBytes(data, from, to)
{
	const out = [];

	for(let i = from; i < to; i++)
	{
		const v = data[i];
		out.push(v === undefined ? 0 : v & 0xFF);
	}

	return out;
}

function padPayload(bytes)
{
	const p = bytes.slice(0, PacketLength - 1);

	while(p.length < PacketLength - 1)
	{
		p.push(0);
	}

	return p;
}

// CRC16-CCITT-FALSE over the 32-byte payload with bytes 6-7 zeroed, stored low byte
// first in bytes 6-7: the vendor frame check of the keyboard (0x0800AC7C) and of the
// receiver updater (tools/srgb_hidtest.py vendor_crc).
function vendorCrc(p)
{
	let c = 0xFFFF;

	for(let i = 0; i < PacketLength - 1; i++)
	{
		c ^= (i === 6 || i === 7 ? 0 : p[i]) << 8;

		for(let b = 0; b < 8; b++)
		{
			c = c & 0x8000 ? ((c << 1) ^ 0x1021) & 0xFFFF : (c << 1) & 0xFFFF;
		}
	}

	return c;
}

function isVendorFrame(p)
{
	return vendorCrc(p) === (p[6] | p[7] << 8);
}

